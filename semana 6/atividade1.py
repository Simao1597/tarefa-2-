print(17 / 5)   
print(17 // 5)  
print(17 % 5)   
print(2 ** 10)


# No C, quando a gente divide dois números inteiros (17 / 5), ele já corta a vírgula e dá 3.
# No Python é diferente: a barra / sempre dá a conta exata com vírgula (3.4).
# Para pegar só a parte inteira no Python, a gente usa duas barras //.